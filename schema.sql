DROP TABLE IF EXISTS items;
DROP TABLE IF EXISTS sessions;
DROP TABLE IF EXISTS messages;
DROP TABLE IF EXISTS usage;
DROP TABLE IF EXISTS library;
DROP TABLE IF EXISTS posts;
DROP TABLE IF EXISTS picks;
DROP TABLE IF EXISTS visits;
DROP TABLE IF EXISTS users;
CREATE TABLE users (id INTEGER PRIMARY KEY AUTOINCREMENT, nickname TEXT NOT NULL UNIQUE COLLATE NOCASE, salt TEXT NOT NULL, pin_hash TEXT NOT NULL, failed INTEGER NOT NULL DEFAULT 0, locked_until INTEGER NOT NULL DEFAULT 0, created_at INTEGER NOT NULL);
CREATE TABLE sessions (token_hash TEXT PRIMARY KEY, user_id INTEGER NOT NULL, created_at INTEGER NOT NULL, expires_at INTEGER NOT NULL);
CREATE INDEX sessions_user ON sessions(user_id);
CREATE TABLE library (user_id INTEGER PRIMARY KEY, items TEXT NOT NULL, updated_at INTEGER NOT NULL);
CREATE TABLE posts (id INTEGER PRIMARY KEY AUTOINCREMENT, user_id INTEGER NOT NULL, kind TEXT NOT NULL, items TEXT NOT NULL, profile TEXT, why TEXT, created_at INTEGER NOT NULL);
CREATE INDEX posts_time ON posts(created_at DESC);
CREATE INDEX posts_user ON posts(user_id);
CREATE TABLE picks (user_id INTEGER NOT NULL, day TEXT NOT NULL, item TEXT NOT NULL, created_at INTEGER NOT NULL, PRIMARY KEY (user_id, day));
CREATE INDEX picks_day ON picks(day);
CREATE TABLE visits (target_id INTEGER NOT NULL, visitor_id INTEGER NOT NULL, day TEXT NOT NULL, PRIMARY KEY (target_id, visitor_id, day));
CREATE TABLE messages (id INTEGER PRIMARY KEY AUTOINCREMENT, to_user_id INTEGER NOT NULL, from_user_id INTEGER NOT NULL, body TEXT NOT NULL, created_at INTEGER NOT NULL);
CREATE INDEX messages_to ON messages(to_user_id, created_at DESC);
CREATE TABLE usage (k TEXT PRIMARY KEY, n INTEGER NOT NULL, exp INTEGER NOT NULL);
